// === - Operadores Logicos - ===

let mayor = true
let suscrito = true 

// AND ( && )

// console.log( true && true )
// console.log( false && true )

console.log ( mayor && suscrito ) // ¿Es "mayor" y "suscrito" verdaderos?

// OR ( || )

console.log ( mayor || suscrito ) // ¿cualquiera de los dos es verdadero?

// NOT ( ! )

console.log( !mayor ) // Cambia el valor de la variable a la contraria ( de true a false o de false a true )